#Нормированное обучающее множество
def get_train_set():
    return [(*normalize(x1, x2, x3, x4, x5), c)
            for x1, x2, x3, x4, x5, c in TRAIN_RAW]

#Нормированные объекты для распознавания
def get_unknown_set():
    return [(name, *normalize(x1, x2, x3, x4, x5))
            for name, x1, x2, x3, x4, x5 in UNKNOWN_RAW]