MAX_X1 = 18.0     # расход топлива, л/100 км
MAX_X2 = 400.0    # мощность, л.с.
MAX_X3 = 6.0      # объём двигателя, л
MAX_X4 = 2500.0   # масса, кг
MAX_X5 = 15.0     # расход масла

FEATURE_MAX = [MAX_X1, MAX_X2, MAX_X3, MAX_X4, MAX_X5]

#Нормировка признаков
def normalize(*features):

    return tuple(f / m for f, m in zip(features, FEATURE_MAX))


